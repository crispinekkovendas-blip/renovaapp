-- Renova — 2026-10-29 — atendimento pelo WhatsApp (triagem com Gemini + ASAAS)
-- Run via Supabase SQL editor. The app role has no DDL privilege.
-- Every statement is idempotent; running it twice is harmless.
--
-- wa_threads   uma conversa por número de WhatsApp (ou simulada, pelo Simulador)
-- wa_cases     um atendimento dentro da conversa: consentimento → triagem →
--              revisão pelo paciente → pagamento → pago → consulta → encerrado
--              (ou recusado / urgente). `triage` é a ficha em JSON (rascunho —
--              só vai para o prontuário quando o médico salva).
-- wa_messages  tudo o que entrou e saiu; `wa_id` é o id da Meta (a Meta reenvia
--              o webhook — o UNIQUE impede mensagem dobrada).

CREATE TABLE IF NOT EXISTS wa_threads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone text NOT NULL UNIQUE,
  contact_name text,
  patient_id bigint REFERENCES patients(id) ON DELETE SET NULL,
  simulated integer NOT NULL DEFAULT 0,
  consent_at timestamptz,
  last_inbound_at timestamptz,
  last_message_at timestamptz,
  unread integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS wa_cases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id bigint NOT NULL REFERENCES wa_threads(id) ON DELETE CASCADE,
  stage text NOT NULL DEFAULT 'consentimento' CHECK (stage IN
    ('consentimento','triagem','revisao','pagamento','pago','consulta','encerrado','recusado','urgente')),
  triage text NOT NULL DEFAULT '{}',
  -- Campo que o questionário (modo sem Gemini) perguntou por último.
  asking text,
  turns integer NOT NULL DEFAULT 0,
  bot_paused integer NOT NULL DEFAULT 0,
  bot_busy_until timestamptz,
  last_error text,
  professional_id bigint REFERENCES professionals(id) ON DELETE SET NULL,
  price_cents integer NOT NULL DEFAULT 0,
  asaas_customer text,
  asaas_payment_id text UNIQUE,
  payment_url text,
  paid_at timestamptz,
  payment_id bigint REFERENCES payments(id) ON DELETE SET NULL,
  consult_started_at timestamptz,
  summary text,
  encounter_id bigint REFERENCES encounters(id) ON DELETE SET NULL,
  closed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_wa_cases_thread ON wa_cases (thread_id, id);
CREATE INDEX IF NOT EXISTS idx_wa_cases_stage ON wa_cases (stage, updated_at);

CREATE TABLE IF NOT EXISTS wa_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id bigint NOT NULL REFERENCES wa_threads(id) ON DELETE CASCADE,
  case_id bigint REFERENCES wa_cases(id) ON DELETE SET NULL,
  direction text NOT NULL CHECK (direction IN ('in','out')),
  -- paciente | robo | equipe | sistema
  author text NOT NULL,
  kind text NOT NULL DEFAULT 'text',
  body text NOT NULL DEFAULT '',
  button_id text,
  wa_id text UNIQUE,
  media_id text,
  mime_type text,
  -- enviado | entregue | lido | erro | simulado (saída); recebido (entrada)
  status text,
  error text,
  handled integer NOT NULL DEFAULT 0,
  user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_wa_messages_thread ON wa_messages (thread_id, id);
CREATE INDEX IF NOT EXISTS idx_wa_messages_pending ON wa_messages (case_id) WHERE direction = 'in' AND handled = 0;

GRANT SELECT, INSERT, UPDATE, DELETE ON wa_threads, wa_cases, wa_messages TO renova_app;
GRANT USAGE, SELECT ON SEQUENCE wa_threads_id_seq, wa_cases_id_seq, wa_messages_id_seq TO renova_app;

ALTER TABLE wa_threads ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_cases ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_messages ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS renova_app_all ON wa_threads;
DROP POLICY IF EXISTS renova_app_all ON wa_cases;
DROP POLICY IF EXISTS renova_app_all ON wa_messages;
CREATE POLICY renova_app_all ON wa_threads FOR ALL TO renova_app USING (true) WITH CHECK (true);
CREATE POLICY renova_app_all ON wa_cases FOR ALL TO renova_app USING (true) WITH CHECK (true);
CREATE POLICY renova_app_all ON wa_messages FOR ALL TO renova_app USING (true) WITH CHECK (true);
